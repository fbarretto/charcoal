import { expect, use } from 'chai';
import chaiAsPromised from 'chai-as-promised';
import { inferPRBody } from '../../src/actions/submit/pr_body';
import { getPRTitle } from '../../src/actions/submit/pr_title';
import { createPrBodyFooter } from '../../src/actions/create_pr_body_footer';
import { TContext } from '../../src/lib/context';
import { stripStackBlock } from '../../src/actions/submit/submit_action';
import { validateNoEmptyBranches } from '../../src/actions/submit/validate_branches';
import { BasicScene } from '../lib/scenes/basic_scene';
import { configureTest } from '../lib/utils/configure_test';

use(chaiAsPromised);

for (const scene of [new BasicScene()]) {
  describe(`(${scene}): correctly infers submit info from commits`, function () {
    configureTest(this, scene);

    it('can infer title/body from single commit', async () => {
      const title = 'Test Title';
      const body = ['Test body line 1.', 'Test body line 2.'].join('\n');
      const message = `${title}\n\n${body}`;

      scene.repo.createChange('a');
      scene.repo.runCliCommand([`create`, `a`, `-m`, message]);

      expect(
        await getPRTitle(
          { branchName: 'a', editPRFieldsInline: false },
          scene.getContext()
        )
      ).to.equals(title);
      expect(
        inferPRBody(
          { branchName: 'a', template: 'template' },
          scene.getContext()
        ).inferredBody
      ).to.equals(`template`);

      scene
        .getContext()
        .userConfig.update((data) => (data.submitIncludeCommitMessages = true));

      expect(
        await getPRTitle(
          { branchName: 'a', editPRFieldsInline: false },
          scene.getContext()
        )
      ).to.equals(title);
      expect(
        inferPRBody(
          { branchName: 'a', template: 'template' },
          scene.getContext()
        ).inferredBody
      ).to.equals(`${body}\n\ntemplate`);
    });

    it('can infer just title with no body', async () => {
      const title = 'Test Title';
      const commitMessage = title;

      scene.repo.createChange('a');
      scene.repo.runCliCommand([`create`, `a`, `-m`, commitMessage]);

      expect(
        await getPRTitle(
          { branchName: 'a', editPRFieldsInline: false },
          scene.getContext()
        )
      ).to.equals(title);
      expect(
        inferPRBody(
          { branchName: 'a', template: 'template' },
          scene.getContext()
        ).inferredBody
      ).to.equal('template');
    });

    it('can infer title/body from multiple commits', async () => {
      const title = 'Test Title';
      const secondSubj = 'Second commit subject';

      scene.repo.createChange('a');
      scene.repo.runCliCommand([`create`, `a`, `-m`, title]);
      scene.repo.createChangeAndCommit(secondSubj);

      expect(
        await getPRTitle(
          { branchName: 'a', editPRFieldsInline: false },
          scene.getContext()
        )
      ).to.equals(title);
      expect(
        inferPRBody({ branchName: 'a' }, scene.getContext()).inferredBody
      ).to.equal(``);

      scene
        .getContext()
        .userConfig.update((data) => (data.submitIncludeCommitMessages = true));

      expect(
        await getPRTitle(
          { branchName: 'a', editPRFieldsInline: false },
          scene.getContext()
        )
      ).to.equals(title);
      expect(
        inferPRBody({ branchName: 'a' }, scene.getContext()).inferredBody
      ).to.equal(`${title}\n\n${secondSubj}`);
    });

    it('aborts if the branch is empty', async () => {
      scene.repo.runCliCommand([`create`, `a`, `-m`, `a`]);
      await expect(validateNoEmptyBranches(['a'], scene.getContext())).to.be
        .rejected;
    });

    it('does not abort if the branch is not empty', async () => {
      scene.repo.createChange('a');
      scene.repo.runCliCommand([`create`, `a`, `-m`, `a`]);
      await expect(validateNoEmptyBranches(['a'], scene.getContext())).to.be
        .fulfilled;
    });
  });
}

describe('stripStackBlock', () => {
  const block =
    '\n\n<!-- charcoal-stack -->\n| | Stack · 1 of 1 | Threads | Status |\n<!-- /charcoal-stack -->';
  const description = `Some PR description

**Changes In This Pull Request:**`;

  it('leaves a body without a block alone', () => {
    expect(stripStackBlock(description)).to.equal(description);
  });

  it('removes every block and keeps content a bot added after it', () => {
    const body = `${description}${block}${block}\n\n---\n_posted by a bot_`;
    expect(stripStackBlock(body)).to.equal(
      `${description}\n\n---\n_posted by a bot_`
    );
  });

  it('removes the old indented dependency tree', () => {
    const legacy =
      '\n\n\n#### PR Dependency Tree\n\n\n* **PR #82**\n  * **PR #83** 👈\n\nThis tree was auto-generated by [Charcoal](https://github.com/danerwilliams/charcoal)';
    expect(stripStackBlock(description + legacy)).to.equal(description);
  });
});

describe('createPrBodyFooter', () => {
  // develop <- a <- b <- c <- e, plus d off b; e has no PR yet.
  const parents: Record<string, string> = {
    a: 'develop',
    b: 'a',
    c: 'b',
    d: 'b',
    e: 'c',
  };
  const numbers: Record<string, number> = { a: 1, b: 2, c: 3, d: 4 };
  const context = {
    engine: {
      trunk: 'develop',
      isTrunk: (b: string) => b === 'develop',
      getParent: (b: string) => parents[b],
      getChildren: (b: string) =>
        Object.keys(parents).filter((c) => parents[c] === b),
      getPrInfo: (b: string) =>
        numbers[b] ? { number: numbers[b] } : undefined,
    },
  } as unknown as TContext;
  const block = (branch: string, details = {}) =>
    createPrBodyFooter(context, branch, {
      details,
      now: new Date('2026-10-13T18:30:00Z'),
    }).split('\n');
  // A row's cells: dot, PR, threads, status.
  const cells = (row: string) =>
    row
      .replace(/^\| | \|$/g, '')
      .split(' | ')
      .map((c) => c.trim());

  it('lists one line top to bottom, current marked, base at the bottom', () => {
    expect(block('b').slice(1, 6)).to.deep.equal([
      '| | Stack · 2 of 3 | Threads | Status |',
      '|:-:|---|---|---|',
      '| ◯ | #3 |  |  |',
      '| ◉ | **#2** 👈 |  |  |',
      '| ◯ | #1 |  |  |',
    ]);
    expect(block('b')[6]).to.equal('| ◯ | `develop` (base) | | |');
    expect(block('b')).to.include(
      '<sub>Updated 2026-10-13 18:30 UTC by `ch submit` · [Charcoal](https://github.com/fbarretto/charcoal)</sub>'
    );
  });

  it('picks one Graphite-style status per PR', () => {
    const label = (cell: string) =>
      cell.replace(/^\$\\color\{#\w+\}\\textsf\{(.*)\}\$$/, '$1');
    const status = (d: object) => label(cells(block('b', { 2: d })[4])[3]);
    const ok = { state: 'OPEN', checks: 'SUCCESS', reviewDecision: 'APPROVED' };
    expect(status({ state: 'MERGED', isDraft: true })).to.equal('merged');
    expect(status({ state: 'CLOSED' })).to.equal('closed');
    expect(status({ ...ok, isDraft: true })).to.equal('draft');
    expect(status({ ...ok, mergeable: 'CONFLICTING' })).to.equal(
      'merge conflicts'
    );
    expect(status({ ...ok, checks: 'FAILURE' })).to.equal(
      'required checks failed'
    );
    expect(status({ ...ok, reviewDecision: 'CHANGES_REQUESTED' })).to.equal(
      'changes requested'
    );
    expect(status({ ...ok, threads: { resolved: 1, total: 2 } })).to.equal(
      'unresolved comments'
    );
    expect(status({ ...ok, checks: 'PENDING' })).to.equal('ci running');
    expect(status({ ...ok, reviewDecision: null })).to.equal('needs review');

    // #1 sits on trunk; #2 and #3 depend on what is below them.
    const statuses = (d: Record<number, object>) =>
      block('b', d)
        .slice(3, 6)
        .map((row) => label(cells(row)[3]));
    expect(statuses({ 1: ok, 2: ok, 3: ok })).to.deep.equal([
      'ready to merge as a stack',
      'ready to merge as a stack',
      'ready to merge',
    ]);
    expect(
      statuses({ 1: { ...ok, checks: 'PENDING' }, 2: ok, 3: ok })
    ).to.deep.equal([
      'waiting on downstack',
      'waiting on downstack',
      'ci running',
    ]);
    expect(statuses({ 1: { state: 'MERGED' }, 2: ok, 3: ok })).to.deep.equal([
      'ready to merge as a stack',
      'ready to merge',
      'merged',
    ]);
  });

  it('shows titles and states in aligned columns', () => {
    const lines = block('b', {
      3: {
        title: 'Add *x*',
        state: 'OPEN',
        checks: 'FAILURE',
        threads: { resolved: 1, total: 2 },
      },
      2: { title: 'Fix y', state: 'MERGED', checks: 'FAILURE' },
    });
    expect(lines[3]).to.equal(
      '| ◯ | #3 Add \\*x\\* | 💬 1/2 | $\\color{#cf222e}\\textsf{required checks failed}$ |'
    );
    expect(lines[4]).to.equal(
      '| ◉ | **#2 Fix y** 👈 |  | $\\color{#8250df}\\textsf{merged}$ |'
    );
  });

  it('adds a copyable list of the stack', () => {
    const lines = block('b', { 3: { title: 'Add *x*' } });
    const start = lines.indexOf('```');
    expect(lines.slice(start, start + 5)).to.deep.equal([
      '```',
      '#3 Add *x*',
      '#2',
      '#1',
      '```',
    ]);
  });
});
